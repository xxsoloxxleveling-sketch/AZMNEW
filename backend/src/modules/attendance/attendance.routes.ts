import { Router } from 'express';
import { Role } from '@prisma/client';
import { attendanceController } from './attendance.controller';
import { examControlRouter } from './examControl.routes';
import { authenticate } from '../../middleware/auth.middleware';
import { authorizeRoles } from '../../middleware/role.middleware';
import { validateBody, validateQuery } from '../../middleware/validate.middleware';
import { attendanceScanRateLimiter } from '../../middleware/rateLimit.middleware';
import { resetScopeSchema, resetConfirmSchema, resetHistorySchema, cancelPreviewSchema, cancelConfirmSchema, cancelHistorySchema, openSessionSchema, closeSessionSchema, reopenSessionSchema, markAttendanceSchema, scanAttendanceSchema, sessionQuerySchema, rosterQuerySchema, todayAttendanceQuerySchema } from './attendance.schema';
const router = Router();
router.use('/control', examControlRouter);
router.use(authenticate, authorizeRoles(Role.SUPER_ADMIN, Role.ADMIN, Role.TEACHER));
const administrators = authorizeRoles(Role.SUPER_ADMIN, Role.ADMIN);
const superAdmin = authorizeRoles(Role.SUPER_ADMIN);
router.post(['/reset/preview','/reset/confirm'], superAdmin, (_req,res) => {res.status(410).json({success:false,message:'Use Exam Session Control to review a reset to PRE_OPEN.'});});
router.get('/reset/history', superAdmin, validateQuery(resetHistorySchema), attendanceController.resetHistory);
router.get('/cancellations/history', superAdmin, validateQuery(cancelHistorySchema), attendanceController.cancelHistory);
router.post('/sessions/:sessionId/cancel/preview', superAdmin, validateBody(cancelPreviewSchema), attendanceController.cancelPreview);
router.post('/sessions/:sessionId/cancel/confirm', superAdmin, attendanceScanRateLimiter, validateBody(cancelConfirmSchema), attendanceController.cancelConfirm);
router.post('/sessions', administrators, validateBody(openSessionSchema), attendanceController.open);
router.get('/sessions', validateQuery(sessionQuerySchema), attendanceController.list);
router.get('/sessions/current-state/:examHallId', administrators, attendanceController.currentHall);
router.get('/sessions/:sessionId/candidates', validateQuery(rosterQuerySchema), attendanceController.candidates);
router.get('/sessions/:sessionId', attendanceController.detail);
router.post('/sessions/:sessionId/mark', attendanceScanRateLimiter, validateBody(markAttendanceSchema), attendanceController.mark);
router.post('/sessions/:sessionId/close', administrators, validateBody(closeSessionSchema), attendanceController.close);
router.post('/sessions/:sessionId/reopen', superAdmin, attendanceScanRateLimiter, validateBody(reopenSessionSchema), attendanceController.reopen);
// Compatibility writes still require an explicit examination session.
router.post('/scan', attendanceScanRateLimiter, validateBody(scanAttendanceSchema), attendanceController.scan);
router.get('/today', validateQuery(todayAttendanceQuerySchema), attendanceController.getToday);
router.get('/student/:id', validateQuery(rosterQuerySchema), attendanceController.getStudentHistory);
export default router;
